// Writes the app list from the folders in apps/core/src/apps, so core never names a
// app itself: `pnpm gen` writes it, `pnpm gen:check` fails when what's on disk is stale.
//
//   apps/core/src/apps/index.generated.ts   imports every app, for core's registry
//   packages/shared/src/apps.generated.ts   each app's meta as data, for the web
//   apps/web/public/logos/<id>.<ext>        each app's logo, at /logos/<id>.<ext>
//   apps/web/lib/app-views.generated.ts         each app's own cards (<view>.card.tsx), for the web
//   apps/web/app/app-themes.generated.css       each app's look (theme.css), for the web
//   .github/CODEOWNERS                         who reviews what, from each meta's maintainers
import { existsSync } from "node:fs";
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";

import * as prettier from "prettier";

import { designTokens, themeProblem } from "../apps/core/src/apps/theme.ts";
import type { AppListing, AppAbout } from "../packages/shared/src/app-about.ts";

const ROOT = path.resolve(import.meta.dirname, "..");
const APPS = path.join(ROOT, "apps/core/src/apps");
const CORE_INDEX = path.join(APPS, "index.generated.ts");
const SHARED_LIST = path.join(ROOT, "packages/shared/src/apps.generated.ts");
// Not under /apps, the Apps page's address, where a guessed address (/apps/aave) redirects.
const LOGOS = path.join(ROOT, "apps/web/public/logos");
const LOGO_FILES = ["logo.svg", "logo.png"];
const APP_VIEWS = path.join(ROOT, "apps/web/lib/app-views.generated.ts");
const VIEW = /^([a-z][a-z0-9-]*)\.card\.tsx$/u;
const APP_THEMES = path.join(ROOT, "apps/web/app/app-themes.generated.css");
const TOKENS = path.join(ROOT, "apps/web/app/tokens.css");
const CODEOWNERS = path.join(ROOT, ".github/CODEOWNERS");
// Auni's own maintainers review everything. An app's maintainers join them on its folder only,
// so core (the box, the card seal, money/) stays theirs alone.
const CORE_OWNERS = ["@jarrodwatts"];
const HANDLE = /^@[\w-]+(?:\/[\w-]+)?$/u;
// about.ts reaches the web as data, so it may name types from @auni/shared and nothing else.
const META_IMPORT = /^import type \{[^}]*\} from "@auni\/shared";$/u;
const HEADER = "// Generated by `pnpm gen` from apps/core/src/apps. Don't edit it by hand.\n";

interface Found {
  readonly meta: AppAbout;
  readonly logo: { readonly file: string; readonly served: string } | null;
  /** Its own cards, by view name: each `<view>.card.tsx` with its `<view>.schema.ts`. */
  readonly views: readonly string[];
  /** Its look, when it brings one: its `theme.css`, checked (apps/theme.ts). */
  readonly theme: string | null;
}

async function readApp(id: string): Promise<Found> {
  const folder = path.join(APPS, id);
  for (const file of ["index.ts", "about.ts"]) {
    if (!existsSync(path.join(folder, file))) throw new Error(`apps/${id} has no ${file}.`);
  }
  const source = await readFile(path.join(folder, "about.ts"), "utf8");
  for (const statement of source.match(
    /^\s*(?:import\b|export\s*(?:\*|\{[^}]*\})\s*from\b)[^;]*;/gmu,
  ) ?? []) {
    if (!META_IMPORT.test(statement.trim().replace(/\s+/gu, " "))) {
      throw new Error(
        `apps/${id}/about.ts may only import types from @auni/shared: ${statement.trim()}`,
      );
    }
  }
  const meta = (
    (await import(pathToFileURL(path.join(folder, "about.ts")).href)) as {
      default: AppAbout;
    }
  ).default;
  if (meta.id !== id) throw new Error(`apps/${id}/about.ts says its id is "${meta.id}".`);
  for (const [name, tool] of Object.entries(meta.tools ?? {})) {
    if (tool.kind !== "recorded" && !tool.copy) {
      throw new Error(`apps/${id}: ${name} is a ${tool.kind} tool, so it needs copy.`);
    }
  }
  for (const handle of meta.maintainers ?? []) {
    if (!HANDLE.test(handle)) {
      throw new Error(`apps/${id}: maintainer "${handle}" isn't a GitHub handle like "@name".`);
    }
  }
  const logo = LOGO_FILES.find((file) => existsSync(path.join(folder, file)));
  const views = (await readdir(folder)).flatMap((file) => VIEW.exec(file)?.[1] ?? []).toSorted();
  for (const view of views) {
    if (!existsSync(path.join(folder, `${view}.schema.ts`))) {
      throw new Error(`apps/${id}/${view}.card.tsx needs ${view}.schema.ts beside it.`);
    }
  }
  const themeFile = path.join(folder, "theme.css");
  const theme = existsSync(themeFile) ? await readFile(themeFile, "utf8") : null;
  const problem = theme && themeProblem(id, theme, designTokens(await readFile(TOKENS, "utf8")));
  if (problem) throw new Error(`apps/${id}/theme.css can't be a look: ${problem}.`);
  return {
    meta,
    logo: logo ? { file: path.join(folder, logo), served: `${id}${path.extname(logo)}` } : null,
    views,
    theme,
  };
}

async function readApps(): Promise<Found[]> {
  const entries = await readdir(APPS, { withFileTypes: true });
  const ids = entries
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .toSorted();
  return Promise.all(ids.map(readApp));
}

function coreIndex(found: readonly Found[]): string {
  const name = (id: string) => id.replace(/-(\w)/gu, (_, letter: string) => letter.toUpperCase());
  const ids = found.map(({ meta }) => meta.id);
  return [
    HEADER,
    `import type { App } from "./contract.ts";`,
    ...ids.map((id) => `import ${name(id)} from "./${id}/index.ts";`),
    "",
    `export const APPS = [${ids.map(name).join(", ")}] as const satisfies readonly App[];`,
  ].join("\n");
}

function sharedList(found: readonly Found[]): string {
  const listings: Record<string, AppListing> = Object.fromEntries(
    found.map(({ meta, logo }) => [
      meta.id,
      { ...meta, ...(logo ? { logo: `/logos/${logo.served}` } : {}) },
    ]),
  );
  const tools = (kind: string) =>
    found.flatMap(({ meta }) =>
      Object.entries(meta.tools ?? {}).flatMap(([name, tool]) =>
        tool.kind === kind ? [name] : [],
      ),
    );
  const list = (values: readonly string[]) => `${JSON.stringify(values)} as const`;
  return [
    HEADER,
    `import type { AppListing } from "./app-about.ts";`,
    "",
    "/** Every app's meta, by id, with where its logo is served. */",
    `export const APP_ABOUTS = ${JSON.stringify(listings)} as const satisfies Readonly<Record<string, AppListing>>;`,
    "",
    "/** The apps' tools by kind, in app order (see ToolMeta.kind). */",
    `export const APP_MONEY_TOOLS = ${list(tools("money"))};`,
    `export const APP_READ_TOOLS = ${list(tools("read"))};`,
    `export const APP_RECORDED_TOOLS = ${list(tools("recorded"))};`,
    `export const APP_LATER_TOOLS = ${list(tools("later"))};`,
    "",
    "/** The apps whose cards wear their own mark. */",
    `export const APP_MARKS = ${list(found.flatMap(({ meta }) => (meta.mark ? [meta.id] : [])))};`,
    "",
    "/** The apps that bring a look the owner can pick (their theme.css). */",
    `export const APP_THEMES = ${list(found.flatMap(({ meta, theme }) => (theme ? [meta.id] : [])))};`,
  ].join("\n");
}

function appViews(found: readonly Found[]): string {
  const name = (id: string, view: string) =>
    `${id}-${view}`.replace(/-(\w)/gu, (_, letter: string) => letter.toUpperCase());
  const withViews = found.filter(({ views }) => views.length);
  const from = (id: string, file: string) => `../../core/src/apps/${id}/${file}`;
  return [
    HEADER,
    `import { appView, type AppView } from "./app-view";`,
    ...withViews.flatMap(({ meta, views }) =>
      views.flatMap((view) => [
        `import ${name(meta.id, view)} from "${from(meta.id, `${view}.card`)}";`,
        `import ${name(meta.id, view)}Data from "${from(meta.id, `${view}.schema`)}";`,
      ]),
    ),
    "",
    "/** Each app's own cards, by app id and view name (see AppCardWire). */",
    `export const APP_VIEWS: Readonly<Record<string, Readonly<Record<string, AppView>>>> = {${withViews
      .map(
        ({ meta, views }) =>
          `${JSON.stringify(meta.id)}: {${views
            .map(
              (view) =>
                `${JSON.stringify(view)}: appView(${name(meta.id, view)}Data, ${name(meta.id, view)})`,
            )
            .join(", ")}}`,
      )
      .join(", ")}};`,
  ].join("\n");
}

/** Every look an app brings, one after another: each is a single rule under its own selector. */
function appThemes(found: readonly Found[]): string {
  return [
    "/* Generated by `pnpm gen` from each app's theme.css. Don't edit it by hand. */",
    ...found.flatMap(({ meta, theme }) => (theme ? [`/* ${meta.name} */\n${theme.trim()}`] : [])),
    "",
  ].join("\n");
}

function codeOwners(found: readonly Found[]): string {
  return [
    "# Generated by `pnpm gen` from each app's about.ts (`maintainers`). Don't edit it by hand.",
    `* ${CORE_OWNERS.join(" ")}`,
    ...found.flatMap(({ meta }) =>
      meta.maintainers?.length
        ? [`/apps/core/src/apps/${meta.id}/ ${[...CORE_OWNERS, ...meta.maintainers].join(" ")}`]
        : [],
    ),
    "",
  ].join("\n");
}

async function formatted(file: string, text: string): Promise<string> {
  const options = await prettier.resolveConfig(file);
  return prettier.format(text, { ...options, filepath: file });
}

/** Every file the app list is, by path, as it should be on disk. */
async function expected(): Promise<Map<string, Buffer>> {
  const found = await readApps();
  const files = new Map<string, Buffer>([
    [CORE_INDEX, Buffer.from(await formatted(CORE_INDEX, coreIndex(found)))],
    [SHARED_LIST, Buffer.from(await formatted(SHARED_LIST, sharedList(found)))],
    [CODEOWNERS, Buffer.from(codeOwners(found))],
    [APP_VIEWS, Buffer.from(await formatted(APP_VIEWS, appViews(found)))],
    [APP_THEMES, Buffer.from(await formatted(APP_THEMES, appThemes(found)))],
  ]);
  for (const { logo } of found) {
    if (logo) files.set(path.join(LOGOS, logo.served), await readFile(logo.file));
  }
  return files;
}

async function logosOnDisk(): Promise<string[]> {
  if (!existsSync(LOGOS)) return [];
  return (await readdir(LOGOS)).map((file) => path.join(LOGOS, file));
}

const files = await expected();
const stale = (await logosOnDisk()).filter((file) => !files.has(file));

if (process.argv.includes("--check")) {
  const changed: string[] = [...stale];
  for (const [file, content] of files) {
    const onDisk = existsSync(file) ? await readFile(file) : null;
    if (!onDisk?.equals(content)) changed.push(file);
  }
  if (changed.length > 0) {
    console.error(
      `The app list is out of date (${changed.map((file) => path.relative(ROOT, file)).join(", ")}): run pnpm gen.`,
    );
    process.exit(1);
  }
} else {
  await mkdir(LOGOS, { recursive: true });
  await Promise.all(stale.map((file) => rm(file)));
  await Promise.all([...files].map(([file, content]) => writeFile(file, content)));
}
